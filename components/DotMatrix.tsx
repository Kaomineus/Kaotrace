export default function DotMatrix({
  value,
  color = "#1e7a46",
  dot = 4,
}: {
  value: string;
  color?: string;
  dot?: number;
}) {
  const gap = Math.max(1, Math.round(dot / 2));
  return (
    <div className="flex" style={{ gap: dot * 1.5 }}>
      {value.split("").map((ch, ci) => {
        const glyph = FONT[ch] ?? FONT[" "];
        return (
          <div
            key={ci}
            className="grid"
            style={{
              gridTemplateColumns: `repeat(5, ${dot}px)`,
              gridTemplateRows: `repeat(7, ${dot}px)`,
              gap,
            }}
          >
            {glyph.map((row, r) =>
              row.split("").map((bit, c) => (
                <div
                  key={r * 5 + c}
                  style={{
                    width: dot,
                    height: dot,
                    borderRadius: "50%",
                    background: bit === "1" ? color : "rgba(25,25,25,0.08)",
                  }}
                />
              ))
            )}
          </div>
        );
      })}
    </div>
  );
}